#!/usr/bin/env node
// Turns the raw results of the UI test run into docs/ui-audit/automated-checks.md:
//   - per flow (spec file): tests passed, failed, skipped (from Playwright's JSON reports);
//   - per screen: axe findings by impact in each of the four views, sideways scroll at 390 px, tab title;
//   - each axe rule that fired, with the screens it fired on.
// Input: test-results/ui/results-<stage>.json and test-results/ui/audit/<screen>.json (both gitignored).
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const resultsDir = path.resolve("test-results/ui");
const auditDir = path.join(resultsDir, "audit");
const out = path.resolve("docs/ui-audit/automated-checks.md");

// Flows: walk every suite of every stage report.
const flows = new Map();
for (const file of existsSync(resultsDir) ? readdirSync(resultsDir).filter((name) => /^results-.*\.json$/.test(name)) : []) {
  const report = JSON.parse(readFileSync(path.join(resultsDir, file), "utf8"));
  const walk = (suite, specFile) => {
    const fileName = suite.file ?? specFile;
    for (const spec of suite.specs ?? []) {
      const row = flows.get(fileName) ?? { passed: 0, failed: 0, skipped: 0, failures: [] };
      for (const t of spec.tests ?? []) {
        const status = t.results?.at(-1)?.status ?? "skipped";
        if (t.expectedStatus === "skipped" || status === "skipped") row.skipped += 1;
        else if (status === "passed") row.passed += 1;
        else { row.failed += 1; row.failures.push(spec.title); }
      }
      flows.set(fileName, row);
    }
    for (const child of suite.suites ?? []) walk(child, fileName);
  };
  for (const suite of report.suites ?? []) walk(suite, suite.file);
}

const screens = existsSync(auditDir) ? readdirSync(auditDir).filter((name) => name.endsWith(".json")).map((name) => JSON.parse(readFileSync(path.join(auditDir, name), "utf8"))) : [];
screens.sort((a, b) => a.screen.localeCompare(b.screen));
const impacts = ["critical", "serious", "moderate", "minor"];
const rules = new Map();
let seriousTotal = 0;

const lines = [
  "# Automated checks (generated)",
  "",
  "Generated by `scripts/ui-test/summarise.mjs` from the last run of `node scripts/ui-test/run.mjs`. Do not edit by hand; the findings with severity and fixes are in [report.md](report.md).",
  "",
  "## Flows",
  "",
  "| Flow (spec) | Passed | Failed | Skipped | Failed tests |",
  "|---|---|---|---|---|",
];
for (const [file, row] of [...flows].sort()) lines.push(`| ${file} | ${row.passed} | ${row.failed} | ${row.skipped} | ${row.failures.join("; ") || "—"} |`);
if (!flows.size) lines.push("| (no Playwright report found) | | | | |");

lines.push("", "## Screens", "", "Axe counts are critical / serious / moderate / minor, for 390 px light, 390 px dark, 1440 px light, 1440 px dark.", "", "| Screen | Axe 390 light | Axe 390 dark | Axe 1440 light | Axe 1440 dark | Sideways scroll at 390 px | Tab title |", "|---|---|---|---|---|---|---|");
for (const screen of screens) {
  const cell = (width, theme) => {
    const view = screen.views.find((v) => v.width === width && v.theme === theme);
    if (!view) return "—";
    for (const finding of view.axe) {
      const entry = rules.get(finding.id) ?? { impact: finding.impact, help: finding.help, screens: new Set() };
      entry.screens.add(screen.screen);
      rules.set(finding.id, entry);
      if (finding.impact === "serious" || finding.impact === "critical") seriousTotal += 1;
    }
    return impacts.map((impact) => view.axe.filter((f) => f.impact === impact).length).join(" / ");
  };
  const narrow = screen.views.filter((v) => v.width === 390);
  const scroll = narrow.some((v) => v.horizontalScroll) ? `yes: ${[...new Set(narrow.flatMap((v) => v.sticksOut))].slice(0, 3).join("; ")}` : "no";
  lines.push(`| [${screen.screen}](screenshots/${screen.screen}-1440-light.jpg) | ${cell(390, "light")} | ${cell(390, "dark")} | ${cell(1440, "light")} | ${cell(1440, "dark")} | ${scroll.replaceAll("|", "\\|")} | ${screen.title.replaceAll("|", "\\|")} |`);
}
lines.push("", `Serious or critical axe findings across all views: **${seriousTotal}**.`, "", "## Axe rules that fired", "", "| Rule | Impact | What it means | Screens |", "|---|---|---|---|");
for (const [id, rule] of [...rules].sort((a, b) => impacts.indexOf(a[1].impact) - impacts.indexOf(b[1].impact))) {
  lines.push(`| ${id} | ${rule.impact} | ${rule.help.replaceAll("|", "\\|")} | ${[...rule.screens].sort().join(", ")} |`);
}
if (!rules.size) lines.push("| (none) | | | |");

writeFileSync(out, `${lines.join("\n")}\n`);
console.log(`Wrote ${path.relative(process.cwd(), out)}: ${flows.size} flows, ${screens.length} screens, ${seriousTotal} serious/critical axe findings.`);
