// Starts the local dual-backend databases, applies every migration to both, gives the plain
// PostgreSQL database its least-privilege app role, and writes .env.test.local.
//
// Usage: node scripts/dev-db/setup.mjs [--reset]
//   --reset  drops both databases' volumes first (all local test data is lost)
//
// Local test only. The generated passwords and JWT secret live in .env.test.local (gitignored)
// and protect containers bound to 127.0.0.1. Never point this script at a real database.
import { createHmac, randomBytes } from "node:crypto";
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import pg from "pg";

const root = process.cwd();
const envFile = path.join(root, ".env.test.local");
const composeFile = path.join(root, "scripts", "dev-db", "compose.yml");
const reset = process.argv.includes("--reset");

function readEnvFile(file) {
  const values = {};
  if (!existsSync(file)) return values;
  for (const rawLine of readFileSync(file, "utf8").split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const eq = line.indexOf("=");
    if (eq > 0) values[line.slice(0, eq).trim()] = line.slice(eq + 1).trim();
  }
  return values;
}

const base64url = (value) => Buffer.from(value).toString("base64url");
function signJwt(payload, secret) {
  const header = base64url(JSON.stringify({ alg: "HS256", typ: "JWT" }));
  const body = base64url(JSON.stringify(payload));
  const signature = createHmac("sha256", secret).update(`${header}.${body}`).digest("base64url");
  return `${header}.${body}.${signature}`;
}

const secret = () => randomBytes(24).toString("hex");
const existing = readEnvFile(envFile);
const env = {
  POLYNOVEA_DEV_ADMIN_PASSWORD: existing.POLYNOVEA_DEV_ADMIN_PASSWORD || secret(),
  POLYNOVEA_DEV_OWNER_PASSWORD: existing.POLYNOVEA_DEV_OWNER_PASSWORD || secret(),
  POLYNOVEA_DEV_APP_PASSWORD: existing.POLYNOVEA_DEV_APP_PASSWORD || secret(),
  POLYNOVEA_DEV_SUPABASE_DB_PASSWORD: existing.POLYNOVEA_DEV_SUPABASE_DB_PASSWORD || secret(),
  POLYNOVEA_DEV_JWT_SECRET: existing.POLYNOVEA_DEV_JWT_SECRET || randomBytes(32).toString("hex"),
};
const now = Math.floor(Date.now() / 1000);
const serviceRoleKey = signJwt({ role: "service_role", iss: "supabase-dev", iat: now, exp: now + 10 * 365 * 24 * 3600 }, env.POLYNOVEA_DEV_JWT_SECRET);
const anonKey = signJwt({ role: "anon", iss: "supabase-dev", iat: now, exp: now + 10 * 365 * 24 * 3600 }, env.POLYNOVEA_DEV_JWT_SECRET);

const adminUrl = `postgresql://polynovea_admin:${env.POLYNOVEA_DEV_ADMIN_PASSWORD}@127.0.0.1:25432/polynovea`;
const ownerUrl = `postgresql://polynovea_owner:${env.POLYNOVEA_DEV_OWNER_PASSWORD}@127.0.0.1:25432/polynovea`;
const appUrl = `postgresql://polynovea_app:${env.POLYNOVEA_DEV_APP_PASSWORD}@127.0.0.1:25432/polynovea`;
const supabaseDbUrl = `postgresql://postgres:${env.POLYNOVEA_DEV_SUPABASE_DB_PASSWORD}@127.0.0.1:25433/postgres`;
const supabaseAdminUrl = `postgresql://supabase_admin:${env.POLYNOVEA_DEV_SUPABASE_DB_PASSWORD}@127.0.0.1:25433/postgres`;

const output = {
  ...env,
  // Direct ("postgres") backend: plain PostgreSQL 16, connected as the app role that cannot run DDL.
  POLYNOVEA_TEST_POSTGRES_URL: appUrl,
  POLYNOVEA_TEST_POSTGRES_OWNER_URL: ownerUrl,
  // Supabase backend: PostgREST over Supabase's PostgreSQL image.
  POLYNOVEA_TEST_SUPABASE_URL: "http://127.0.0.1:25480",
  POLYNOVEA_TEST_SUPABASE_SERVICE_ROLE_KEY: serviceRoleKey,
  POLYNOVEA_TEST_SUPABASE_ANON_KEY: anonKey,
  POLYNOVEA_TEST_SUPABASE_DB_URL: supabaseDbUrl,
};
writeFileSync(
  envFile,
  "# Generated by scripts/dev-db/setup.mjs for local tests only. Gitignored; do not commit or reuse.\n"
    + Object.entries(output).map(([key, value]) => `${key}=${value}`).join("\n") + "\n",
  { mode: 0o600 },
);

const compose = (...args) => execFileSync("docker", ["compose", "-f", composeFile, "--env-file", envFile, ...args], { stdio: "inherit" });
if (reset) compose("down", "-v");
compose("up", "-d", "--wait");

function runMigrations(databaseUrl) {
  execFileSync(process.execPath, ["scripts/run-migrations.mjs", "--all"], {
    stdio: "inherit",
    env: { ...process.env, DATABASE_URL: databaseUrl, Database_URL: "", database_url: "" },
  });
}

async function withClient(url, fn) {
  const client = new pg.Client({ connectionString: url, ssl: false });
  try {
    await client.connect();
  } catch (error) {
    if (url === adminUrl && error?.code === "28P01") {
      throw new Error("The local database was created before polynovea_admin existed. Run: node scripts/dev-db/setup.mjs --reset");
    }
    throw error;
  }
  try {
    return await fn(client);
  } finally {
    await client.end();
  }
}

// Plain PostgreSQL, as the one-time admin login: the Supabase role names the migrations grant to
// (anon, authenticated, service_role and postgres) must exist until phase 1's migration 0067
// replaces them. polynovea_owner is not a superuser: it owns schema public and may create schemas,
// so migrations and tests hit the same privilege errors they would on RDS or Azure.
// The runtime role gets rows and functions only.
await withClient(adminUrl, async (client) => {
  await client.query(`
    do $$ begin
      if not exists (select 1 from pg_roles where rolname = 'polynovea_owner') then create role polynovea_owner login nosuperuser nocreatedb nocreaterole; end if;
      if not exists (select 1 from pg_roles where rolname = 'anon') then create role anon nologin; end if;
      if not exists (select 1 from pg_roles where rolname = 'authenticated') then create role authenticated nologin; end if;
      if not exists (select 1 from pg_roles where rolname = 'service_role') then create role service_role nologin; end if;
      if not exists (select 1 from pg_roles where rolname = 'postgres') then create role postgres nologin; end if;
      if not exists (select 1 from pg_roles where rolname = 'polynovea_app') then create role polynovea_app login; end if;
    end $$;
  `);
  await client.query(`alter role polynovea_owner with login nosuperuser password '${env.POLYNOVEA_DEV_OWNER_PASSWORD.replace(/'/g, "''")}'`);
  await client.query(`alter role polynovea_app with login password '${env.POLYNOVEA_DEV_APP_PASSWORD.replace(/'/g, "''")}'`);
  await client.query("grant connect, create on database polynovea to polynovea_owner");
  await client.query("alter schema public owner to polynovea_owner");
  await client.query("revoke create on schema public from public");
});
runMigrations(ownerUrl);
await withClient(ownerUrl, async (client) => {
  await client.query(`
    grant usage on schema public to polynovea_app;
    grant select, insert, update, delete on all tables in schema public to polynovea_app;
    grant usage, select on all sequences in schema public to polynovea_app;
    grant execute on all functions in schema public to polynovea_app;
    alter default privileges in schema public grant select, insert, update, delete on tables to polynovea_app;
    alter default privileges in schema public grant usage, select on sequences to polynovea_app;
    alter default privileges in schema public grant execute on functions to polynovea_app;
  `);
  // Every table has row-level security enabled with no policies. Supabase's service_role has
  // BYPASSRLS; polynovea_app does not, so without a policy it would read nothing and write nothing.
  // A permissive policy per table (what phase 1's migration 0067 must do) keeps the app role free of
  // BYPASSRLS, which managed databases may not let the installer grant anyway.
  await client.query(`
    do $$
    declare t record;
    begin
      for t in
        select c.relname from pg_class c join pg_namespace n on n.oid = c.relnamespace
        where n.nspname = 'public' and c.relkind in ('r', 'p') and c.relrowsecurity
      loop
        if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = t.relname and policyname = 'polynovea_app_all') then
          execute format('create policy polynovea_app_all on public.%I for all to polynovea_app using (true) with check (true)', t.relname);
        end if;
      end loop;
    end $$;
  `);
});

// Supabase-compatible database: PostgREST logs in as `authenticator` and GoTrue as
// `supabase_auth_admin` (only supabase_admin may set their passwords).
await withClient(supabaseAdminUrl, async (client) => {
  const password = env.POLYNOVEA_DEV_SUPABASE_DB_PASSWORD.replace(/'/g, "''");
  await client.query(`alter role authenticator with login password '${password}'`);
  await client.query(`alter role supabase_auth_admin with login password '${password}'`);
});
runMigrations(supabaseDbUrl);
await withClient(supabaseDbUrl, (client) => client.query("notify pgrst, 'reload schema'"));
compose("restart", "postgrest", "gotrue", "rest-gateway");

console.log("\nLocal databases ready. Test settings written to .env.test.local.");
