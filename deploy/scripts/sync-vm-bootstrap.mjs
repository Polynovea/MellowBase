#!/usr/bin/env node
// Builds deploy/scripts/vm-bootstrap.sh from the release package's VM files, and copies it into the
// places that need it (the CloudFormation user data and the OpenTofu modules). The release package
// owns those files (systemd units, run scripts, Caddyfile, provision.sh); the templates never write
// their own, so a plain Ubuntu server ends up exactly like the Polynovea server image.
//
//   node deploy/scripts/sync-vm-bootstrap.mjs                  # from the repo's release package files
//   node deploy/scripts/sync-vm-bootstrap.mjs --from <dir> ... # from other folders (searched in order)
//   node deploy/scripts/sync-vm-bootstrap.mjs --git <commit>   # from a commit of the release package
//   node deploy/scripts/sync-vm-bootstrap.mjs --check          # exit 1 if anything is out of date
//
// deploy/templates.test.ts runs the same check whenever the release package's files are present.
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { gzipSync } from "node:zlib";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");

/** Where the release package keeps its VM files, searched in order. */
export const DEFAULT_SOURCES = ["release/packer/files", "release/packer", "docker"];

/** The files provision.sh installs (it expects them all in one folder), then provision.sh itself. */
export const VM_FILES = [
  "20auto-upgrades",
  "52polynovea-unattended-upgrades",
  "daemon.json",
  "journald-polynovea.conf",
  "run-cms.sh",
  "run-caddy.sh",
  "has-domain.sh",
  "data-disk.sh",
  "console-code.sh",
  "Caddyfile",
  "polynovea-data-disk.service",
  "var-lib-polynovea.mount",
  "polynovea-console-code.service",
  "polynovea.service",
  "polynovea-caddy.service",
  "provision.sh",
];

export const OUTPUT = "deploy/scripts/vm-bootstrap.sh";
export const COPIES = ["deploy/opentofu/modules/aws/vm-bootstrap.sh", "deploy/opentofu/modules/azure/vm-bootstrap.sh"];
export const CFN = "deploy/aws/polynovea.yaml";
const BEGIN = "# BEGIN GENERATED vm-bootstrap";
const END = "# END GENERATED vm-bootstrap";
const FILE_END = "POLYNOVEA_FILE_END";
const SCRIPT_END = "POLYNOVEA_BOOTSTRAP_END";

/** Finds each VM file in the source folders. Returns null when the release package isn't present. */
export function findSources(sources = DEFAULT_SOURCES, root = ROOT) {
  const found = {};
  for (const name of VM_FILES) {
    const dir = sources.find((d) => existsSync(path.resolve(root, d, name)));
    if (!dir) return null;
    found[name] = path.resolve(root, dir, name);
  }
  return found;
}

/** The bootstrap script's text, from the VM files' contents. */
export function renderBootstrap(contents) {
  const parts = [];
  const digest = createHash("sha256");
  for (const name of VM_FILES) {
    const text = contents[name].replace(/\r\n/g, "\n").replace(/\n?$/, "\n");
    if (text.includes(FILE_END) || text.includes(SCRIPT_END)) throw new Error(`${name} contains a reserved heredoc marker`);
    digest.update(`${name}\0${text}`);
    parts.push(`cat > "$FILES/${name}" <<'${FILE_END}'\n${text}${FILE_END}\n`);
  }
  return `#!/bin/sh
# GENERATED by deploy/scripts/sync-vm-bootstrap.mjs from the release package's VM files. Do not edit:
# change those files and run the script again. Files sha256: ${digest.digest("hex")}
#
# First boot of a Polynovea server made by a cloud template. The template has already written
# /etc/polynovea/polynovea.env (non-secret values only) and passes the cloud (aws or azure) as $1.
# - On a Polynovea server image everything is installed: start it again so it reads the new settings.
# - On plain Ubuntu 24.04, install exactly what the server image installs (provision.sh), then start it.
#
# Fails closed: images are pulled only by digest, and if any step fails (a pull, a check, the
# signature check) the CMS and Caddy are stopped and disabled, so nothing unverified runs, even
# after a reboot. The log is in journalctl -u polynovea-bootstrap.
set -eu
CLOUD="\${1:?usage: vm-bootstrap.sh aws|azure}"
ENV_FILE=/etc/polynovea/polynovea.env
VERIFY=/opt/polynovea/verify-images.sh

fail_closed() {
  status=$?
  if [ "$status" -ne 0 ]; then
    echo "polynovea-bootstrap: failed (exit $status); the CMS stays stopped" >&2
    systemctl disable --now polynovea.service polynovea-caddy.service >/dev/null 2>&1 || true
  fi
  exit "$status"
}
trap fail_closed EXIT

value() { sed -n "s/^$1=//p" "$ENV_FILE" | tail -1 | tr -d '"'"'"'[:space:]'; }
for key in POLYNOVEA_IMAGE_REF POLYNOVEA_CADDY_IMAGE_REF; do
  ref="$(value "$key")"
  case "$ref" in
    "" | *@sha256:*) ;;
    *) echo "polynovea-bootstrap: $key must be pinned by digest (name@sha256:...)" >&2; exit 1 ;;
  esac
done

if [ ! -f /etc/systemd/system/polynovea.service ]; then
  FILES=/tmp/polynovea-files
  rm -rf "$FILES"
  install -d -m 0700 "$FILES"
${parts.join("")}
  # provision.sh installs, pulls by digest and, with POLYNOVEA_START_NOW=1, starts the units itself.
  POLYNOVEA_IMAGE_REF="$(value POLYNOVEA_IMAGE_REF)" \\
  POLYNOVEA_CADDY_IMAGE_REF="$(value POLYNOVEA_CADDY_IMAGE_REF)" \\
  POLYNOVEA_RELEASE_ID=cloud-template \\
  POLYNOVEA_CLOUD="$CLOUD" \\
  POLYNOVEA_FILES="$FILES" \\
  POLYNOVEA_START_NOW=1 \\
    sh "$FILES/provision.sh"
  STARTED=1
else
  STARTED=0
fi

# The release package's signature check, when it provides one (exit non-zero = refuse to start;
# on plain Ubuntu the units are already starting, and the trap above stops and disables them).
if [ -x "$VERIFY" ]; then
  "$VERIFY"
else
  echo "polynovea-bootstrap: no $VERIFY in this release; images are trusted by digest only" >&2
fi

# A Polynovea server image started its units at boot, before user data wrote the settings: restart
# them so they read the settings.
if [ "$STARTED" = 0 ]; then
  systemctl daemon-reload
  systemctl start polynovea-data-disk.service var-lib-polynovea.mount
  systemctl restart polynovea-console-code.service polynovea.service polynovea-caddy.service
fi
`;
}

/**
 * How a template starts the bootstrap. It runs as its own systemd unit, not inside cloud-init:
 * provision.sh waits for cloud-init to finish, which would never happen from inside it.
 */
export const START_COMMAND = (cloud) => `systemd-run --unit=polynovea-bootstrap --description="Polynovea first boot" /bin/sh /usr/local/sbin/polynovea-bootstrap ${cloud}`;

/**
 * The CloudFormation template with its generated user-data block replaced. EC2 user data is limited
 * to 16 KB, so the script goes in gzipped and base64-encoded; deploy/scripts/vm-bootstrap.sh is the
 * readable copy, and deploy/templates.test.ts checks the two match.
 */
export function renderCfn(cfn, bootstrap) {
  const lines = cfn.split("\n");
  const begin = lines.findIndex((l) => l.trim() === BEGIN);
  const end = lines.findIndex((l) => l.trim() === END);
  if (begin < 0 || end < begin) throw new Error(`${CFN} has no ${BEGIN} ... ${END} block`);
  const indent = lines[begin].slice(0, lines[begin].indexOf("#"));
  const packed = gzipSync(Buffer.from(bootstrap, "utf8"), { level: 9 }).toString("base64").match(/.{1,76}/g);
  const sha = createHash("sha256").update(bootstrap).digest("hex");
  const body = [
    `# deploy/scripts/vm-bootstrap.sh (sha256 ${sha}), gzipped and base64-encoded to fit EC2's 16 KB limit.`,
    `base64 -d > /usr/local/sbin/polynovea-bootstrap.gz <<'${SCRIPT_END}'`,
    ...packed,
    SCRIPT_END,
    "gunzip -f /usr/local/sbin/polynovea-bootstrap.gz",
    START_COMMAND("aws"),
  ];
  return [...lines.slice(0, begin + 1), ...body.map((l) => indent + l), ...lines.slice(end)].join("\n");
}

/** Every generated file's expected text, keyed by repo path. */
export function expectedOutputs(contents, root = ROOT) {
  const bootstrap = renderBootstrap(contents);
  const out = { [OUTPUT]: bootstrap };
  for (const copy of COPIES) out[copy] = bootstrap;
  out[CFN] = renderCfn(readFileSync(path.resolve(root, CFN), "utf8"), bootstrap);
  return out;
}

/** The VM files' contents at a git commit (DEFAULT_SOURCES layout). Null when any is missing. */
export function contentsAtCommit(rev, root = ROOT) {
  const contents = {};
  for (const name of VM_FILES) {
    const text = DEFAULT_SOURCES.map((dir) => {
      try {
        return execFileSync("git", ["show", `${rev}:${dir}/${name}`], { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] });
      } catch {
        return null;
      }
    }).find((t) => t !== null);
    if (text == null) return null;
    contents[name] = text;
  }
  return contents;
}

function main(argv) {
  const check = argv.includes("--check");
  const from = argv.flatMap((a, i) => (argv[i - 1] === "--from" ? [a] : []));
  const rev = argv[argv.indexOf("--git") + 1];
  let contents;
  if (argv.includes("--git")) {
    if (!rev || !/^[A-Za-z0-9._/-]+$/.test(rev)) {
      console.error("--git needs a commit, branch or tag");
      process.exit(2);
    }
    contents = contentsAtCommit(rev);
    if (!contents) {
      console.error(`The release package's VM files were not all found at ${rev} in: ${DEFAULT_SOURCES.join(", ")}`);
      process.exit(2);
    }
  } else {
    const sources = findSources(from.length ? from.map((d) => path.resolve(d)) : DEFAULT_SOURCES);
    if (!sources) {
      console.error(`The release package's VM files were not found in: ${(from.length ? from : DEFAULT_SOURCES).join(", ")}`);
      process.exit(2);
    }
    contents = Object.fromEntries(Object.entries(sources).map(([name, file]) => [name, readFileSync(file, "utf8")]));
  }
  const stale = [];
  for (const [file, text] of Object.entries(expectedOutputs(contents))) {
    const target = path.resolve(ROOT, file);
    const current = existsSync(target) ? readFileSync(target, "utf8") : null;
    if (current === text) continue;
    stale.push(file);
    if (!check) writeFileSync(target, text);
  }
  if (check && stale.length) {
    console.error(`Out of date: ${stale.join(", ")}. Run: node deploy/scripts/sync-vm-bootstrap.mjs`);
    process.exit(1);
  }
  console.log(stale.length ? `${check ? "stale" : "wrote"}: ${stale.join(", ")}` : "up to date");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv.slice(2));
